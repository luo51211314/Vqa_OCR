#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""从 results_repro 自动生成论文延迟表（tab:latency_block 同构）。

布局与论文一致：
  行 = Model × Setting(w/o OCR, w/ OCR)
  列 = MyDataVQA / ChartQA / DocVQA，每个数据集 Time(s) + ΔT
时间取每格 metrics.json -> time_stats.avg_time（端到端口径，含 OCR）；
std/p50/p95 保留在同目录 CSV 供正文引用。缺格 TBD，禁止人工填数。

    python scripts/make_latency_table.py --root results_repro/<run>/main_table
"""
import argparse
import glob
import json
import os

import pandas as pd

# (列顺序, dataset, split)
DATASETS = [
    ("MyDataVQA", "mydatavqa", "test"),
    ("ChartQA", "chartqa", "test"),
    ("DocVQA", "docvqa", "val"),
]
# (显示名, model_type)
MODELS = [("LLaVA", "llava"), ("mplug3-owl", "mplug"), ("Qwen", "qwen")]


def collect(root):
    """返回 {(dataset, model, variant): (avg, std, p50, p95, n, path)}。"""
    cells = {}
    for path in glob.glob(os.path.join(root, "**", "*_metrics.json"), recursive=True):
        rel_parts = os.path.relpath(path, root).split(os.sep)
        if any(part.startswith(("_", ".")) for part in rel_parts[:-1]) \
                or "table3" in rel_parts[:-1]:
            continue
        with open(path, encoding="utf-8") as f:
            m = json.load(f)
        ri = m.get("run_info")
        if ri is None:
            continue
        variant = "off" if m.get("use_experts") in ("off", "none", None) else "ocr"
        if variant == "ocr":
            phi = ri.get("phi") or {}
            if phi.get("order") != "native" or phi.get("template") != "p2" \
                    or phi.get("budget_tokens") or phi.get("sample_ids_file"):
                continue  # 消融格不进延迟主表
        ts = m.get("time_stats") or {}
        if ts.get("avg_time") is None:
            continue
        key = (ri["dataset"], ri["model_type"], variant)
        ts_newer = ri.get("timestamp", "")
        if key not in cells or ts_newer > cells[key][-1]:
            cells[key] = (
                ts.get("avg_time"), ts.get("std_time"),
                ts.get("median_time"), ts.get("p95_time"),
                ts.get("n_samples"), path, ri.get("timestamp", ""),
            )
    return cells


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True)
    ap.add_argument("--outdir", default=None)
    args = ap.parse_args()
    outdir = args.outdir or os.path.join(args.root, "table3")
    os.makedirs(outdir, exist_ok=True)

    cells = collect(args.root)
    rows = []
    tex = [
        r"% generated by scripts/make_latency_table.py; 端到端 avg latency (s/sample)",
        r"\begin{table*}[t]",
        r"\centering",
        r"\caption{Inference latency comparison with and without OCR enhancement "
        r"across models and datasets.}",
        r"\label{tab:latency_block}",
        r"\resizebox{\linewidth}{!}{",
        r"\begin{tabular}{llcc|cc|cc}",
        r"\toprule",
        r" &  & \multicolumn{2}{c|}{MyDataVQA} & \multicolumn{2}{c|}{ChartQA} "
        r"& \multicolumn{2}{c}{DocVQA} \\",
        r"\cmidrule(lr){3-4} \cmidrule(lr){5-6} \cmidrule(lr){7-8}",
        r"Model & Setting "
        r"& Time (s) & $\Delta T$ "
        r"& Time (s) & $\Delta T$ "
        r"& Time (s) & $\Delta T$ \\",
        r"\midrule",
    ]

    for mi, (disp, model) in enumerate(MODELS):
        tex.append(r"\multirow{2}{*}{" + disp + "}")
        for setting, variant in (("w/o OCR", "off"), ("w/ OCR", "ocr")):
            row = {"model": model, "setting": variant}
            cells_tex = []
            for col_name, ds, _split in DATASETS:
                item = cells.get((ds, model, variant))
                off_item = cells.get((ds, model, "off"))
                if item is None:
                    row[f"{ds}_time"] = "TBD"
                    row[f"{ds}_delta"] = "TBD"
                    cells_tex.append(("TBD", "--" if variant == "off" else "TBD"))
                else:
                    avg = item[0]
                    row[f"{ds}_time"] = round(avg, 3)
                    row[f"{ds}_std"] = item[1]
                    row[f"{ds}_p50"] = item[2]
                    row[f"{ds}_p95"] = item[3]
                    row[f"{ds}_n"] = item[4]
                    if variant == "off":
                        cells_tex.append((f"{avg:.2f}", "--"))
                    elif off_item is not None:
                        dt = avg - off_item[0]
                        row[f"{ds}_delta"] = round(dt, 3)
                        cells_tex.append((f"{avg:.2f}", f"{dt:+.2f}"))
                    else:
                        row[f"{ds}_delta"] = "TBD"
                        cells_tex.append((f"{avg:.2f}", "TBD"))
            rows.append(row)
            flat = " & ".join(f"{t} & {d}" for t, d in cells_tex)
            tex.append(f"& {setting} & {flat} \\\\")
        if mi < len(MODELS) - 1:
            tex.append(r"\midrule")

    tex += [
        r"\bottomrule",
        r"\end{tabular}",
        r"}",
        r"\end{table*}",
        "",
    ]

    csv_path = os.path.join(outdir, "table_latency.csv")
    pd.DataFrame(rows).to_csv(csv_path, index=False)
    tex_path = os.path.join(outdir, "table_latency.tex")
    with open(tex_path, "w", encoding="utf-8") as f:
        f.write("\n".join(tex) + "\n")
    print(f"-> {csv_path}\n-> {tex_path}")


if __name__ == "__main__":
    main()
